using CollegeMS.Data;
using CollegeMS.Models;
using CollegeMS.Services;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Http.Features;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;

var builder = WebApplication.CreateBuilder(args);

var cs = builder.Configuration.GetConnectionString("DefaultConnection")
    ?? throw new InvalidOperationException("Connection string 'DefaultConnection' is missing in appsettings.json");
builder.Services.AddDbContext<AppDbContext>(o =>
    o.UseNpgsql(cs).ConfigureWarnings(w => w.Ignore(RelationalEventId.PendingModelChangesWarning)));

builder.Services.AddIdentity<ApplicationUser, IdentityRole>(o =>
{
    o.Password.RequiredLength = 8;
    o.Password.RequireDigit = true;
    o.Password.RequireUppercase = true;
    o.Password.RequireLowercase = true;
    o.Password.RequireNonAlphanumeric = false;
    o.User.RequireUniqueEmail = false;
    o.Lockout.MaxFailedAccessAttempts = 5;
    o.Lockout.DefaultLockoutTimeSpan = TimeSpan.FromMinutes(10);
}).AddEntityFrameworkStores<AppDbContext>().AddDefaultTokenProviders();

builder.Services.Configure<SecurityStampValidatorOptions>(o => o.ValidationInterval = TimeSpan.Zero);

builder.Services.ConfigureApplicationCookie(o =>
{
    o.LoginPath = "/Account/Login";
    o.AccessDeniedPath = "/Account/AccessDenied";
    o.ExpireTimeSpan = TimeSpan.FromHours(8);
    o.SlidingExpiration = true;
    o.Cookie.HttpOnly = true;
});

builder.Services.AddControllersWithViews(o =>
{
    o.SuppressImplicitRequiredAttributeForNonNullableReferenceTypes = true;
    o.Filters.Add(new Microsoft.AspNetCore.Mvc.AutoValidateAntiforgeryTokenAttribute());
    o.MaxModelBindingCollectionSize = 5000; // timetable import preview posts one item per class
});
builder.Services.Configure<FormOptions>(o => { o.MultipartBodyLengthLimit = 20 * 1024 * 1024; o.ValueCountLimit = 30000; });
builder.Services.AddMemoryCache();
builder.Services.AddHttpContextAccessor();
builder.Services.AddScoped<AuditService>();
builder.Services.AddScoped<FileService>();
builder.Services.AddScoped<NumberService>();
builder.Services.AddScoped<CurrentPerson>();
builder.Services.AddScoped<AccountProvisioner>();
builder.Services.AddScoped<AnalyticsService>();
builder.Services.AddScoped<ReportBuilder>();
builder.Services.AddScoped<AttendanceService>();
builder.Services.AddScoped<ExamService>();
builder.Services.AddScoped<ExamPlannerService>();
builder.Services.AddScoped<ExamCalendarService>();
builder.Services.AddScoped<NoticeAudienceService>();
builder.Services.AddScoped<FeeService>();
builder.Services.AddScoped<TeacherScheduleService>();
builder.Services.AddSingleton<SiteService>();
builder.Services.AddSingleton<ReportService>();

var app = builder.Build();

if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Home/Error");
    if (!builder.Configuration.GetValue<bool>("DisableHttpsRedirect")) app.UseHsts();
}
app.UseStatusCodePagesWithReExecute("/Home/StatusCode", "?code={0}");
app.Use(async (ctx, next) =>
{
    ctx.Response.Headers["X-Content-Type-Options"] = "nosniff";
    ctx.Response.Headers["X-Frame-Options"] = "SAMEORIGIN";
    ctx.Response.Headers["Referrer-Policy"] = "strict-origin-when-cross-origin";
    await next();
});
// HTTPS redirection is skipped in Development and whenever "DisableHttpsRedirect": true (plain-HTTP LAN demo).
if (!app.Environment.IsDevelopment() && !builder.Configuration.GetValue<bool>("DisableHttpsRedirect")) app.UseHttpsRedirection();
app.UseStaticFiles();
app.UseRouting();
app.UseAuthentication();
app.UseAuthorization();

app.MapControllerRoute("areas", "{area:exists}/{controller=Dashboard}/{action=Index}/{id?}");
app.MapControllerRoute("page", "p/{slug}", new { controller = "Site", action = "Page" });
app.MapControllerRoute("default", "{controller=Home}/{action=Index}/{id?}");

using (var scope = app.Services.CreateScope())
{
    var log = scope.ServiceProvider.GetRequiredService<ILogger<Program>>();
    try
    {
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await db.Database.MigrateAsync();
        // A null CourseId represents a college-wide examination (All courses).
        try { await db.Database.ExecuteSqlRawAsync("ALTER TABLE \"Examinations\" ALTER COLUMN \"CourseId\" DROP NOT NULL"); } catch { }
        try
        {
            await db.Database.ExecuteSqlRawAsync(@"
                CREATE TABLE IF NOT EXISTS ""Complaints"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT NOW(),
                    ""UpdatedAt"" timestamp with time zone NULL,
                    ""IsDeleted"" boolean NOT NULL DEFAULT FALSE,
                    ""TicketNo"" character varying(50) NOT NULL,
                    ""Subject"" character varying(150) NOT NULL,
                    ""Category"" character varying(60) NOT NULL,
                    ""TargetAuthority"" character varying(40) NOT NULL,
                    ""Description"" character varying(2000) NOT NULL,
                    ""Status"" character varying(40) NOT NULL DEFAULT 'Open',
                    ""SubmitterUserId"" character varying(100) NOT NULL,
                    ""SubmitterName"" character varying(150) NOT NULL,
                    ""SubmitterRole"" character varying(50) NOT NULL,
                    ""SubmitterDepartmentId"" integer NULL,
                    ""TargetDepartmentId"" integer NULL,
                    ""TargetTeacherId"" integer NULL,
                    ""Response"" character varying(2000) NULL,
                    ""RespondedByName"" character varying(150) NULL,
                    ""RespondedByUserId"" character varying(100) NULL,
                    ""RespondedAt"" timestamp with time zone NULL
                )");
        }
        catch { }
        try
        {
            await db.Database.ExecuteSqlRawAsync(@"
                CREATE TABLE IF NOT EXISTS ""TeacherAbsences"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT NOW(),
                    ""UpdatedAt"" timestamp with time zone NULL,
                    ""IsDeleted"" boolean NOT NULL DEFAULT FALSE,
                    ""TeacherId"" integer NOT NULL,
                    ""Date"" date NOT NULL,
                    ""Note"" character varying(250) NULL
                )");
        }
        catch { }
        await SeedData.InitializeAsync(scope.ServiceProvider);
    }
    catch (Exception ex)
    {
        log.LogCritical(ex, "Database initialization failed. Check the PostgreSQL connection string in appsettings.json.");
        throw;
    }
}

app.Run();
